export type UiKey = keyof typeof fr;
const strings: Record<Locale, typeof fr> = { fr, en };

export function translate(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  const text = strings[locale][key];
  return vars
    ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
    : text;
}

/** UI strings for the current language. Game content is translated by the engine. */
export function useT() {
  const { locale } = useSettings();
  return (key: UiKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
}
